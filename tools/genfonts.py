# ---- GFX fonts: ASCII 0x20..0x7E then Georgian 0x7F..0x9F
def gfx(bdfpath, name, src):
    g,asc,desc=load(bdfpath)
    codes=list(range(0x20,0x7f))+GEO
    bm=[]; gl=[]
    for k,cp in enumerate(codes):
        c=g[cp]; w,h,xo,yo=c['bbx']; B=bits(c)
        # trim empty rows/cols for tight packing
        off=len(bm)
        # trim blank rows/cols (BBX in these BDFs is the full cell) to save flash
        rows=[y for y in range(h) if any(B[y])]; cols=[x for x in range(w) if any(B[y][x] for y in range(h))]
        if rows:
            r0,r1,c0,c1=rows[0],rows[-1]+1,cols[0],cols[-1]+1
            B=[row[c0:c1] for row in B[r0:r1]]
            yo=yo+(h-r1); xo=xo+c0; w=c1-c0; h=r1-r0
        bitsflat=[B[y][x] for y in range(h) for x in range(w)]
        if not any(bitsflat): w=h=0; xo=yo=0; bitsflat=[]
        acc=0;n=0
        for v in bitsflat:
            acc=(acc<<1)|v; n+=1
            if n==8: bm.append(acc); acc=0;n=0
        if n: bm.append(acc<<(8-n))
        label = chr(cp) if cp!=0x5c else 'backslash'
        gl.append('  { %5d, %3d, %3d, %3d, %4d, %4d }, // 0x%02X %s U+%04X'%(off,w,h,c['dw'],xo,-(yo+h) if h else 0,0x20+k,label,cp))
    first,last=0x20,0x20+len(codes)-1
    bmtxt=',\n'.join('  '+', '.join('0x%02X'%b for b in bm[i:i+16]) for i in range(0,len(bm),16))
    yadv=asc+desc
    txt=f'''// {name}: Adafruit_GFX font with ASCII 0x20..0x7E plus the 33 Georgian Mkhedruli
// letters mapped to codes 0x7F..0x9F (ა=0x7F ... ჰ=0x9F). Use through GeorgianGFX, which
// converts UTF-8 to this encoding automatically.
// Glyph source: Markus Kuhn's public-domain ucs-fonts "{src}". Generated by tools/genfonts.py.
// All tables live in PROGMEM (flash) on AVR. Size: {len(bm)} bitmap bytes + {len(codes)*7} glyph-table bytes.
#pragma once
#include <Adafruit_GFX.h>

static const uint8_t {name}Bitmaps[] PROGMEM = {{
{bmtxt}
}};

static const GFXglyph {name}Glyphs[] PROGMEM = {{
  // bitmapOffset, width, height, xAdvance, xOffset, yOffset
{chr(10).join(gl)}
}};

static const GFXfont {name} PROGMEM = {{
  (uint8_t *){name}Bitmaps, (GFXglyph *){name}Glyphs, 0x{first:02X}, 0x{last:02X}, {yadv}
}};
// Baseline is {asc} px below the top of a text line; line height {yadv} px.
'''
    open(f'{LIB}/fonts/{name}.h','w').write(txt)
    print(name, len(bm), 'bitmap bytes, line', yadv, 'asc', asc)
